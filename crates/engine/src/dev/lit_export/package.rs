//! The files of the npm package around the components: `package.json`, `tsconfig.json`, `index.ts`
//! and `README.md`.

use serde_json::json;

pub const DEFAULT_NAME: &str = "uigen-lib";
pub const DEFAULT_VERSION: &str = "0.1.0";

const MAX_NAME: usize = 214;
const MAX_VERSION: usize = 64;
const LIT_RANGE: &str = "^3.2.0";
const TYPESCRIPT_RANGE: &str = "^5.6.0";

fn url_safe(part: &str) -> bool {
    !part.is_empty()
        && !part.starts_with(['.', '_'])
        && part.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '-' | '.' | '_' | '~'))
}

/// Whether `name` is a name npm accepts for a new package: lowercase, URL-safe, `@scope/name` allowed.
pub fn valid_name(name: &str) -> bool {
    if name.chars().count() > MAX_NAME {
        return false;
    }
    match name.strip_prefix('@') {
        Some(scoped) => scoped.split_once('/').is_some_and(|(scope, rest)| url_safe(scope) && url_safe(rest)),
        None => url_safe(name),
    }
}

/// Whether `version` is a semantic version: `1.2.3`, with an optional `-pre` and `+build`.
pub fn valid_version(version: &str) -> bool {
    if version.len() > MAX_VERSION {
        return false;
    }
    let (core, extra) = version.split_at(version.find(['-', '+']).unwrap_or(version.len()));
    let numbers: Vec<&str> = core.split('.').collect();
    numbers.len() == 3
        && numbers.iter().all(|n| !n.is_empty() && n.len() <= 9 && n.bytes().all(|b| b.is_ascii_digit()) && (*n == "0" || !n.starts_with('0')))
        && extra.len() != 1
        && extra.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '+' | '.'))
}

fn pretty(value: &serde_json::Value) -> String {
    format!("{}\n", serde_json::to_string_pretty(value).unwrap_or_default())
}

/// `package.json`; its keys are sorted at every level.
pub fn manifest(name: &str, version: &str) -> String {
    pretty(&json!({
        "name": name,
        "version": version,
        "type": "module",
        "main": "dist/index.js",
        "types": "dist/index.d.ts",
        "scripts": {"build": "tsc"},
        "dependencies": {"lit": LIT_RANGE},
        "devDependencies": {"typescript": TYPESCRIPT_RANGE},
    }))
}

pub fn tsconfig() -> String {
    pretty(&json!({
        "compilerOptions": {
            "target": "ES2021",
            "module": "ES2022",
            "moduleResolution": "bundler",
            "lib": ["ES2021", "DOM", "DOM.Iterable"],
            "declaration": true,
            "outDir": "dist",
            "rootDir": ".",
            "strict": true,
            "skipLibCheck": true,
            "experimentalDecorators": true,
            "useDefineForClassFields": false,
        },
        "include": ["index.ts", "components/**/*.ts"],
    }))
}

/// `index.ts`: one re-export per element, in the order of `tags`.
pub fn index(tags: &[&str]) -> String {
    if tags.is_empty() {
        return "export {};\n".to_string();
    }
    tags.iter().map(|tag| format!("export * from \"./components/{tag}.js\";\n")).collect()
}

/// `README.md`; `elements` are (tag, class) pairs.
pub fn readme(name: &str, elements: &[(&str, &str)]) -> String {
    let mut out = format!("# {name}\n\nLit web components generated by UIGEN.\n\n## Use\n\n");
    out.push_str("Load the design tokens once, then import the components:\n\n");
    out.push_str(&format!("```ts\nimport \"{name}/tokens/tokens.css\";\nimport \"{name}\";\n```\n\n"));
    out.push_str("Build the package with `npm install` and `npm run build`.\n\n## Components\n\n");
    if elements.is_empty() {
        out.push_str("None yet.\n");
    }
    for (tag, class) in elements {
        out.push_str(&format!("- `<{tag}>` (`{class}`)\n"));
    }
    out
}
