//! Writing the Lit package into a folder that may also hold files its owner keeps by hand. The
//! folder's `.uigen/export.json` lists what a previous export generated and the hash of each file:
//! a later export replaces only a listed file whose content is still that hash, and says what it
//! left alone. Nothing is ever deleted. The disk is reached only through [`crate::file_access`].

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use figcraft_plugin::bundle::sha256_hex;
use serde::{Deserialize, Serialize};

use super::ExportPlan;
use crate::file_access;
use crate::lit::Note;
use crate::{EngineError, Result};

pub const MANIFEST: &str = ".uigen/export.json";
const GENERATOR: &str = "uigen-lit";
const VERSION: u64 = 1;
const MAX_MANIFEST: u64 = 4 << 20;
const MAX_FILE: u64 = 64 << 20;
const MAX_WALKED: usize = 10_000;
const MAX_DEPTH: usize = 8;
const NOT_WALKED: [&str; 3] = ["node_modules", "dist", ".git"];

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Reason {
    /// Generated by an export, then changed by hand.
    Edited,
    /// There before any export, under a name the package uses.
    NotGenerated,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Skipped {
    pub path: String,
    pub reason: Reason,
}

/// What a write did, every path relative to the folder and `/`-separated.
#[derive(Clone, Debug, Default, PartialEq, Serialize)]
pub struct WriteReport {
    pub written: Vec<String>,
    pub unchanged: Vec<String>,
    /// Files the export did not generate, left as they are.
    pub kept: Vec<String>,
    pub skipped: Vec<Skipped>,
    /// Generated by an earlier export, no longer produced, left in place.
    pub stale: Vec<String>,
    #[serde(skip)]
    pub notes: Vec<Note>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct Manifest {
    version: u64,
    generator: String,
    files: Vec<Entry>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct Entry {
    path: String,
    sha256: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    component: Option<String>,
}

fn valid_path(path: &str) -> bool {
    path != MANIFEST && !path.is_empty() && !path.contains(['\\', ':', '\0']) && path.split('/').all(|part| !matches!(part, "" | "." | ".."))
}

fn valid_hash(hash: &str) -> bool {
    hash.len() == 64 && hash.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

fn parse(bytes: &[u8]) -> std::result::Result<BTreeMap<String, Entry>, String> {
    let manifest: Manifest = serde_json::from_slice(bytes).map_err(|e| format!("it is not an export manifest ({e})"))?;
    if manifest.version != VERSION {
        return Err(format!("it is version {}, this export reads version {VERSION}", manifest.version));
    }
    let mut listed = BTreeMap::new();
    for entry in manifest.files {
        if !valid_path(&entry.path) || !valid_hash(&entry.sha256) {
            return Err(format!("it lists an invalid entry ({})", entry.path.escape_debug()));
        }
        listed.insert(entry.path.clone(), entry);
    }
    Ok(listed)
}

fn note(message: String) -> Note {
    Note { code: "manifest-ignored", component: String::new(), layer: None, message }
}

fn hash_of(path: &Path) -> Result<Option<String>> {
    if !file_access::exists(path) {
        return Ok(None);
    }
    Ok(Some(sha256_hex(&file_access::read_capped(path, MAX_FILE)?)))
}

fn put(path: &Path, bytes: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent() {
        file_access::create_dir_all(parent)?;
    }
    file_access::write(path, bytes)
}

fn fold(path: &str) -> String {
    if cfg!(windows) { path.to_ascii_lowercase() } else { path.to_string() }
}

fn through_link(root: &Path, rel: &str) -> bool {
    let mut at = root.to_path_buf();
    rel.split('/').any(|part| {
        at.push(part);
        file_access::is_link(&at)
    })
}

/// The files of `dir` the export did not generate, and whether the walk stopped early.
fn kept_files(dir: &Path, known: &BTreeSet<String>) -> Result<(Vec<String>, bool)> {
    let mut found = Vec::new();
    let mut pending = vec![String::new()];
    let mut walked = 0;
    while let Some(rel) = pending.pop() {
        let at = if rel.is_empty() { dir.to_path_buf() } else { dir.join(&rel) };
        for entry in file_access::read_dir(&at)? {
            walked += 1;
            if walked > MAX_WALKED {
                found.sort();
                return Ok((found, true));
            }
            let Some(name) = entry.file_name().map(|n| n.to_string_lossy().into_owned()) else { continue };
            let path = if rel.is_empty() { name } else { format!("{rel}/{name}") };
            let folded = fold(&path);
            let linked = file_access::is_link(dir.join(&path));
            if !linked && file_access::is_dir(dir.join(&path)) {
                let skip = NOT_WALKED.contains(&fold(name_of(&path)).as_str()) || folded == ".uigen" || path.matches('/').count() >= MAX_DEPTH;
                if !skip {
                    pending.push(path);
                }
            } else if !known.contains(&folded) {
                found.push(path);
            }
        }
    }
    found.sort();
    Ok((found, false))
}

fn name_of(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Write the files of `plan` into folder `dir` (created when missing), the manifest last. A file
/// the folder already has is replaced only when the manifest lists it and nobody changed it, or
/// with `force`; `plan` must be [ready](ExportPlan::ready).
pub fn write(plan: &ExportPlan, dir: &str, force: bool) -> Result<WriteReport> {
    let root = Path::new(dir);
    if let Some(path) = plan.files.iter().map(|f| f.path.as_str()).chain([MANIFEST]).find(|path| through_link(root, path)) {
        return Err(EngineError::Other(format!("{path}: a link inside {dir} leads out of it, nothing was written")));
    }
    file_access::create_dir_all(root)?;
    let manifest_path = root.join(MANIFEST);
    let before = if file_access::exists(&manifest_path) { Some(file_access::read_capped(&manifest_path, MAX_MANIFEST)) } else { None };
    let mut report = WriteReport::default();
    let listed = match before.as_ref().map(|read| read.as_ref().map_err(ToString::to_string).and_then(|bytes| parse(bytes))) {
        None => BTreeMap::new(),
        Some(Ok(listed)) => listed,
        Some(Err(why)) => {
            report.notes.push(note(format!(
                "{MANIFEST} was ignored: {why}. Nothing it could have listed is replaced unless `force` is set, and a new one is written"
            )));
            BTreeMap::new()
        }
    };

    let mut entries: BTreeMap<String, Entry> = BTreeMap::new();
    let mut to_write = Vec::new();
    for file in &plan.files {
        let hash = sha256_hex(file.text.as_bytes());
        let component = plan.components.iter().find(|c| c.file.as_deref() == Some(file.path.as_str())).map(|c| c.name.clone());
        let ours = Entry { path: file.path.clone(), sha256: hash.clone(), component };
        let old = listed.get(&file.path);
        match (hash_of(&root.join(&file.path))?, old) {
            (Some(on_disk), _) if on_disk == hash => {
                report.unchanged.push(file.path.clone());
                entries.insert(file.path.clone(), ours);
            }
            (Some(on_disk), Some(old)) if on_disk != old.sha256 && !force => {
                report.skipped.push(Skipped { path: file.path.clone(), reason: Reason::Edited });
                entries.insert(file.path.clone(), old.clone());
            }
            (Some(_), None) if !force => report.skipped.push(Skipped { path: file.path.clone(), reason: Reason::NotGenerated }),
            _ => {
                to_write.push(file);
                entries.insert(file.path.clone(), ours);
            }
        }
    }

    let planned: BTreeSet<&str> = plan.files.iter().map(|f| f.path.as_str()).collect();
    for (path, old) in &listed {
        if !planned.contains(path.as_str()) && file_access::exists(root.join(path)) {
            report.stale.push(path.clone());
            entries.insert(path.clone(), old.clone());
        }
    }
    let known: BTreeSet<String> = planned.iter().copied().chain(report.stale.iter().map(String::as_str)).map(fold).collect();
    let (kept, truncated) = kept_files(root, &known)?;
    report.kept = kept;
    if truncated {
        report.notes.push(Note {
            code: "kept-truncated",
            component: String::new(),
            layer: None,
            message: format!("The folder has more than {MAX_WALKED} entries: the list of files the export did not generate is partial"),
        });
    }

    for file in to_write {
        put(&root.join(&file.path), file.text.as_bytes())?;
        report.written.push(file.path.clone());
    }
    let manifest = Manifest { version: VERSION, generator: GENERATOR.to_string(), files: entries.into_values().collect() };
    let mut text = serde_json::to_string_pretty(&manifest).map_err(|e| EngineError::Other(format!("{MANIFEST}: {e}")))?;
    text.push('\n');
    if matches!(&before, Some(Ok(bytes)) if bytes == text.as_bytes()) {
        report.unchanged.push(MANIFEST.to_string());
    } else {
        put(&manifest_path, text.as_bytes())?;
        report.written.push(MANIFEST.to_string());
    }
    Ok(report)
}
