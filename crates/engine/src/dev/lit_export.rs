//! The Lit export of a file: `tokens.css`, the custom properties its components read. Light values
//! are on `:root`; the dark mode, when there is one, twice (for the system setting, unless the page
//! asks for the light theme, and for `data-theme="dark"`) with only what differs from light; every
//! other mode of a collection on `[data-<collection>="<mode>"]`. Names come from
//! [`crate::codegen::LitNames`], the ones the components use.

use std::collections::HashSet;

use figcraft_doc::{Collection, Document, Mode, VariableValue};

use crate::cmd::variables_io::css_value;
use crate::codegen::{LitNames, css_var_name};
use crate::lit::{Note, css_string};
use crate::token_roles::Roles;

const HEADER: &str = "/* Generated by UIGEN. Do not edit: your changes are kept only if you rename the file. */";
const LIGHT_MODES: &[&str] = &["light", "clair", "day"];
const DARK_MODES: &[&str] = &["dark", "sombre", "night"];
const TOKENS_FILE: &str = "tokens.css";

/// How the tokens are written: the custom property prefix (`ui` → `--ui-colors-brand`), and the
/// names of the light and dark modes (found by their usual names when left out).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TokenOptions {
    pub prefix: String,
    pub light: Option<String>,
    pub dark: Option<String>,
}

/// `tokens.css`, the custom properties it declares (in order) and what it could not do.
#[derive(Clone, Debug, PartialEq)]
pub struct TokensCss {
    pub text: String,
    pub declared: Vec<String>,
    pub notes: Vec<Note>,
}

/// `text` as the content of a CSS string: nothing in it closes the string, opens or closes a
/// comment, or breaks the line.
fn css_text(text: &str) -> String {
    let printable: String = text.chars().filter(|c| !c.is_control() || *c == '\n').collect();
    css_string(&printable).replace("/*", "/\\*").replace("*/", "*\\/")
}

fn named(c: &Collection, matches: impl Fn(&str) -> bool) -> Option<&Mode> {
    c.modes.iter().find(|m| matches(m.name.trim()))
}

fn light_of<'a>(c: &'a Collection, wanted: Option<&str>) -> Option<&'a Mode> {
    wanted
        .and_then(|w| named(c, |n| n.eq_ignore_ascii_case(w.trim())))
        .or_else(|| named(c, |n| LIGHT_MODES.iter().any(|l| n.eq_ignore_ascii_case(l))))
        .or_else(|| c.modes.first())
}

fn dark_of<'a>(c: &'a Collection, wanted: Option<&str>, light: &Mode) -> Option<&'a Mode> {
    let found = match wanted {
        Some(w) => named(c, |n| n.eq_ignore_ascii_case(w.trim())),
        None => named(c, |n| DARK_MODES.iter().any(|d| n.eq_ignore_ascii_case(d))),
    };
    found.filter(|m| m.id != light.id)
}

type Block = (String, Vec<String>);

fn push_line(blocks: &mut Vec<Block>, selector: &str, line: String) {
    match blocks.iter_mut().find(|(s, _)| s == selector) {
        Some((_, lines)) => lines.push(line),
        None => blocks.push((selector.to_string(), vec![line])),
    }
}

fn rule(out: &mut String, selector: &str, lines: &[String], depth: usize) {
    let pad = "  ".repeat(depth);
    out.push_str(&format!("{pad}{selector} {{\n"));
    for line in lines {
        out.push_str(&format!("{pad}  {line}\n"));
    }
    out.push_str(&format!("{pad}}}\n"));
}

/// `colls` as `tokens.css`.
pub fn tokens_css(doc: &Document, colls: &[&Collection], opts: &TokenOptions) -> TokensCss {
    let vars = &doc.variables;
    let names = LitNames::new(doc, &opts.prefix);
    let roles = Roles::new(doc);
    let declared: Vec<String> = colls.iter().flat_map(|c| vars.variables.iter().filter(|v| v.collection == c.id)).map(|v| names.name(v)).collect();
    let known: HashSet<&String> = declared.iter().collect();
    let (mut root, mut dark, mut others): (Vec<String>, Vec<String>, Vec<Block>) = (Vec::new(), Vec::new(), Vec::new());
    let (mut notes, mut has_dark) = (Vec::new(), false);
    for c in colls {
        let Some(light) = light_of(c, opts.light.as_deref()) else { continue };
        let dark_mode = dark_of(c, opts.dark.as_deref(), light);
        has_dark |= dark_mode.is_some();
        let attribute = css_var_name(&c.name);
        let attribute = attribute.trim_start_matches('-');
        for v in vars.variables.iter().filter(|v| v.collection == c.id) {
            let name = names.name(v);
            for target in v.values.values().filter_map(|x| if let VariableValue::Alias(a) = x { vars.get(a) } else { None }) {
                let missing = names.name(target);
                let note = Note {
                    code: "token-missing",
                    component: TOKENS_FILE.to_string(),
                    layer: None,
                    message: format!("{name} refers to {} ({missing}), which {TOKENS_FILE} does not declare", target.name),
                };
                if !known.contains(&missing) && !notes.contains(&note) {
                    notes.push(note);
                }
            }
            let value = |m: &Mode| css_value(vars, &roles, v, &m.id, css_text, |t| names.name(t));
            let base = value(light);
            if let Some(b) = &base {
                root.push(format!("{name}: {b};"));
            }
            if let Some(d) = dark_mode.and_then(value).filter(|d| base.as_ref() != Some(d)) {
                dark.push(format!("{name}: {d};"));
            }
            for m in c.modes.iter().filter(|m| m.id != light.id && dark_mode.is_none_or(|d| d.id != m.id)) {
                if let Some(o) = value(m).filter(|o| base.as_ref() != Some(o)) {
                    push_line(&mut others, &format!("[data-{attribute}=\"{}\"]", css_text(&m.name)), format!("{name}: {o};"));
                }
            }
        }
    }
    if !has_dark && colls.iter().any(|c| c.modes.len() > 1) {
        notes.push(Note {
            code: "no-dark-mode",
            component: TOKENS_FILE.to_string(),
            layer: None,
            message: "no dark mode found: name one in darkMode, or add a mode called Dark".to_string(),
        });
    }
    let mut text = format!("{HEADER}\n");
    if !root.is_empty() {
        text.push('\n');
        rule(&mut text, ":root", &root, 0);
    }
    if !dark.is_empty() {
        text.push_str("\n@media (prefers-color-scheme: dark) {\n");
        rule(&mut text, ":root:not([data-theme=\"light\"])", &dark, 1);
        text.push_str("}\n\n");
        rule(&mut text, "[data-theme=\"dark\"]", &dark, 0);
    }
    for (selector, lines) in &others {
        text.push('\n');
        rule(&mut text, selector, lines, 0);
    }
    TokensCss { text, declared, notes }
}
