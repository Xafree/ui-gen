//! Lit design tokens: components read `var(--<prefix>-<name>)` with no fallback, and
//! `lit_export::tokens_css` writes the `tokens.css` that declares every one of them (light values
//! on `:root`, dark ones twice, once for the system setting and once for `data-theme`).
//! `variable.export` keeps its own output (see `lit_tokens_freeze_tests`).

use crate::Session;
use crate::components::tests::{ex, idv};
use crate::lit_export::{TokenOptions, TokensCss, tokens_css};
use figcraft_doc::{Collection, NodeId};
use serde_json::{Value, json};

const HEADER: &str = "/* Generated by UIGEN. Do not edit: your changes are kept only if you rename the file. */";
const DARK_SCHEME: &str = "@media (prefers-color-scheme: dark) {";
const DARK_UNLESS_LIGHT: &str = ":root:not([data-theme=\"light\"])";
const DARK_ATTRIBUTE: &str = "[data-theme=\"dark\"]";

fn options(light: Option<&str>, dark: Option<&str>) -> TokenOptions {
    TokenOptions { prefix: "ui".to_string(), light: light.map(str::to_string), dark: dark.map(str::to_string) }
}

fn export(s: &Session, collections: &[&str], o: &TokenOptions) -> TokensCss {
    let doc = s.doc().unwrap();
    let found: Vec<&Collection> = collections.iter().map(|name| doc.variables.collection(name).unwrap()).collect();
    tokens_css(doc, &found, o)
}

