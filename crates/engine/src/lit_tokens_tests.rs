/// A component `name`: an auto layout frame with two rectangles, "Bg" and "Bg2", each filled red.
/// `binds` are (layer, field, variable) where layer is "root", "Bg" or "Bg2".
fn card(s: &mut Session, name: &str, binds: &[(&str, &str, &str)]) -> NodeId {
    let frame = idv(&ex(s, "frame.create", json!({"x": 0, "y": 0, "width": 100, "height": 100, "name": name})));
    ex(s, "layout.add", json!({"ids": [frame]}));
    let mut layers = vec![("root", frame)];
    for (i, layer) in ["Bg", "Bg2"].into_iter().enumerate() {
        let rect = idv(&ex(
            s,
            "shape.rectangle",
            json!({"x": 0, "y": i * 40, "width": 100, "height": 40, "parent": frame, "props": {"name": layer, "fill": "#ff0000"}}),
        ));
        layers.push((layer, rect));
    }
    for (layer, field, variable) in binds {
        let id = layers.iter().find(|(l, _)| l == layer).map(|(_, id)| *id).unwrap();
        ex(s, "variable.bind", json!({"ids": [id], "field": field, "variable": variable}));
    }
    idv(&ex(s, "component.create", json!({"ids": [frame]})))
}

fn lit(s: &mut Session, component: NodeId) -> Value {
    ex(s, "inspect.componentCode", json!({"id": component, "language": "lit"}))
}

fn definition(v: &Value) -> String {
    v["definition"].as_str().unwrap_or_default().to_string()
}

fn compact(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn has_note(notes: &Value, code: &str) -> bool {
    notes.as_array().is_some_and(|all| all.iter().any(|n| n["code"] == code))
}

/// Every `var(...)` in `text`: (custom property, whether a fallback follows it).
fn vars_in(text: &str) -> Vec<(String, bool)> {
    text.match_indices("var(")
        .map(|(at, _)| {
            let rest = text.get(at + 4..).unwrap_or_default();
            let inner = rest.split(')').next().unwrap_or_default();
            (inner.split(',').next().unwrap_or_default().trim().to_string(), inner.contains(','))
        })
        .collect()
}

/// The trimmed, lowercased declaration lines of the first rule whose selector is `selector`.
fn block(text: &str, selector: &str) -> Option<Vec<String>> {
    let mut lines = text.lines().map(str::trim);
    let opening = format!("{selector} {{");
    lines.find(|line| *line == opening)?;
    Some(lines.take_while(|line| *line != "}").filter(|line| !line.is_empty() && !line.starts_with("/*")).map(str::to_lowercase).collect())
}

fn declares(lines: &[String], declaration: &str) -> bool {
    lines.iter().any(|line| line == declaration)
}

fn unescaped_quotes(line: &str) -> usize {
    let (mut count, mut slashes) = (0, 0);
    for c in line.chars() {
        match c {
            '\\' => slashes += 1,
            '"' => {
                if slashes % 2 == 0 {
                    count += 1;
                }
                slashes = 0;
            }
            _ => slashes = 0,
        }
    }
    count
}

#[test]
fn a_bound_fill_is_a_prefixed_var_without_fallback() {
    // covers: E6-3.1
    let mut s = Session::new();
    colors(&mut s);
    metrics(&mut s);
    let c = card(&mut s, "Card", &[("Bg", "fill", "Colors/Brand 500"), ("root", "gap", "Space/sm"), ("Bg", "cornerRadius", "Radius/md")]);
    let v = lit(&mut s, c);
    let def = definition(&v);
    let text = compact(&def);
    for want in ["background: var(--ui-colors-brand-500);", "gap: var(--ui-space-sm);", "border-radius: var(--ui-radius-md);"] {
        assert!(text.contains(want), "{want:?}:\n{def}");
    }
    assert!(!def.to_lowercase().contains("3366ff"), "the hex value stays out of the component:\n{def}");
    let used = vars_in(&def);
    assert!(used.len() >= 3, "{def}");
    assert!(used.iter().all(|(_, fallback)| !fallback), "no var() has a fallback:\n{def}");
    assert!(!has_note(&v["notes"], "code-syntax-ignored"), "{v}");

    let acme = ex(&mut s, "inspect.componentCode", json!({"id": c, "language": "lit", "prefix": "acme-"}));
    let acme = compact(&definition(&acme));
    assert!(acme.contains("background: var(--acme-colors-brand-500);"), "the token prefix follows the tag prefix:\n{acme}");
    assert!(!acme.contains("--ui-"), "{acme}");

    let tokens = export(&s, &["Colors", "Metrics"], &options(None, None));
    for name in ["--ui-colors-brand-500", "--ui-space-sm", "--ui-radius-md"] {
        assert!(tokens.declared.iter().any(|d| d == name), "{name} is declared: {:?}", tokens.declared);
    }
}

#[test]
fn web_code_syntax_is_ignored_in_lit_and_kept_elsewhere() {
    // covers: E6-3.2
    let mut s = Session::new();
    colors(&mut s);
    ex(&mut s, "variable.create", json!({"collection": "Colors", "name": "Colors/Primary", "type": "color", "value": "#112233"}));
    ex(&mut s, "variable.update", json!({"variable": "Colors/Primary", "codeSyntax": {"WEB": "var(--brand-primary)"}}));
    let c = card(&mut s, "Card", &[("Bg2", "fill", "Colors/Primary")]);

    let v = lit(&mut s, c);
    let def = definition(&v);
    assert!(compact(&def).contains("background: var(--ui-colors-primary);"), "{def}");
    assert!(!def.contains("brand-primary"), "{def}");
    let notes = v["notes"].as_array().cloned().unwrap_or_default();
    let note = notes.iter().find(|n| n["code"] == "code-syntax-ignored").unwrap_or_else(|| panic!("a code-syntax-ignored note: {notes:?}"));
    assert_eq!(note["component"], "Card", "{note}");
    let message = note["message"].as_str().unwrap_or_default();
    assert!(message.contains("brand-primary") || message.contains("Colors/Primary"), "the note names what was ignored: {note}");

    for language in ["react", "vue", "leptos"] {
        let other = ex(&mut s, "inspect.componentCode", json!({"id": c, "language": language}));
        assert!(definition(&other).contains("var(--brand-primary"), "{language} keeps the Web code syntax:\n{}", definition(&other));
    }
    let kids = s.doc().unwrap().node(c).unwrap().children.clone();
    let bg2 = kids.into_iter().find(|k| s.doc().unwrap().node(*k).unwrap().name == "Bg2").unwrap();
    let css = ex(&mut s, "inspect.code", json!({"id": bg2, "language": "css"}));
    assert!(css["code"].as_str().unwrap_or_default().contains("var(--brand-primary"), "css keeps it: {css}");

    let tokens = export(&s, &["Colors"], &options(None, None));
    assert!(tokens.declared.iter().any(|d| d == "--ui-colors-primary"), "{:?}", tokens.declared);
    assert!(!tokens.text.contains("brand-primary"), "{}", tokens.text);
}

#[test]
fn tokens_css_has_light_on_root_and_only_the_differences_in_both_dark_blocks() {
    // covers: E6-3.3
    let mut s = Session::new();
    colors(&mut s);
    let tokens = export(&s, &["Colors"], &options(None, None));
    let text = &tokens.text;
    assert_eq!(text.lines().next(), Some(HEADER), "{text}");

    let root = block(text, ":root").unwrap_or_else(|| panic!("a :root rule:\n{text}"));
    for want in ["--ui-colors-brand-500: #3366ff;", "--ui-colors-surface: #ffffff;", "--ui-colors-accent: var(--ui-colors-brand-500);"] {
        assert!(declares(&root, want), "{want:?} on :root:\n{text}");
    }

    assert!(text.contains(DARK_SCHEME), "{text}");
    let dark = vec!["--ui-colors-brand-500: #6699ff;".to_string()];
    assert_eq!(block(text, DARK_UNLESS_LIGHT), Some(dark.clone()), "the system dark block holds only what differs:\n{text}");
    assert_eq!(block(text, DARK_ATTRIBUTE), Some(dark), "the data-theme block is identical:\n{text}");
    assert!(!declares(&root, "--ui-colors-brand-500: #6699ff;"), "{text}");

    let at = |needle: &str| text.find(needle).unwrap_or_else(|| panic!("{needle:?} in\n{text}"));
    assert!(at(":root {") < at(DARK_SCHEME) && at(DARK_SCHEME) < at(DARK_ATTRIBUTE), "{text}");
    assert_eq!(text.matches(":root {").count(), 1, "one :root rule:\n{text}");
}

