#[test]
fn names_that_collide_get_a_numeric_suffix_in_both_files() {
    // covers: E6-3.1
    let mut s = Session::new();
    ex(&mut s, "variable.createCollection", json!({"name": "Palette", "modes": ["Base"]}));
    ex(&mut s, "variable.create", json!({"collection": "Palette", "name": "Brand 500", "type": "color", "value": "#111111"}));
    ex(&mut s, "variable.create", json!({"collection": "Palette", "name": "Brand-500", "type": "color", "value": "#222222"}));
    let c = card(&mut s, "Card", &[("Bg", "fill", "Brand 500"), ("Bg2", "fill", "Brand-500")]);
    let tokens = export(&s, &["Palette"], &options(None, None));
    assert_eq!(tokens.declared.len(), 2, "{:?}", tokens.declared);
    assert_eq!(tokens.declared.first().map(String::as_str), Some("--ui-brand-500"), "the first keeps the plain name");
    let second = tokens.declared.get(1).cloned().unwrap_or_default();
    let suffix = second.strip_prefix("--ui-brand-500-").unwrap_or_else(|| panic!("a numeric suffix: {second}"));
    assert!(!suffix.is_empty() && suffix.chars().all(|ch| ch.is_ascii_digit()), "{second}");

    let root = block(&tokens.text, ":root").unwrap_or_else(|| panic!("{}", tokens.text));
    assert!(declares(&root, "--ui-brand-500: #111111;"), "{}", tokens.text);
    assert!(declares(&root, &format!("{second}: #222222;")), "{}", tokens.text);

    let text = compact(&definition(&lit(&mut s, c)));
    assert!(text.contains("background: var(--ui-brand-500);"), "{text}");
    assert!(text.contains(&format!("background: var({second});")), "the component reads the name the file declares:\n{text}");
}
